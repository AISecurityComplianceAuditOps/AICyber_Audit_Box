BURP_PDF = """1. External service interaction (HTTP)
Next
Summary
Severity: High
Confidence: Certain
Host: https://shop.test
Path: /catalog
Issue detail
It is possible to induce the application to perform server-side HTTP requests.
Request 1
GET /catalog HTTP/2
Host: shop.test
Response 1
HTTP/2 200 OK
Content-Length: 3
Collaborator HTTP interaction
The Collaborator server received an HTTP request.
Request to Collaborator
GET / HTTP/1.1
2. Client-side template injection
Previous
Summary
Severity: High
Confidence: Firm
Host: https://shop.test
Path: /search
Issue detail
The HTML page uses AngularJS v1.7.7. This proof-of-concept attack demonstrates an injection.
"""


def _burp_pdf():
    a, i = BurpParser()._parse_plaintext(BURP_PDF)
    return {f.title.split(" (")[0]: f for f in a + i}


def test_the_pdf_collaborator_interaction_is_its_own_part():
    ev = _burp_pdf()["External service interaction"].evidence
    assert "[HTTP Response 1]\nHTTP/2 200 OK\nContent-Length: 3" in ev
    assert "[Collaborator HTTP interaction]\nThe Collaborator server received an HTTP request." in ev


def test_a_version_number_does_not_end_the_description():
    assert "This proof-of-concept attack demonstrates" in _burp_pdf()["Client-side template injection"].description


PARTIAL = """Burp Scanner Sample Report
6. External service interaction (HTTP)
https://shop.test/catalog/product/stock [Referer HTTP header]
Severity: High
Confidence: Firm
Host: https://shop.test
Path: /catalog/product/stock
Issue detail
It is possible to induce requests.
7. Vulnerable JavaScript dependency
Severity: Medium
Issue detail
The application uses a JavaScript library with known vulnerabilities.
"""


def test_an_unnumbered_instance_line_is_not_the_title():
    a, i = BurpParser()._parse_plaintext(PARTIAL)
    titles = sorted(f.title for f in a + i)
    assert titles[0].startswith("External service interaction (HTTP) (https://shop.test/catalog/product/stock")


def test_a_finding_naming_no_host_does_not_take_the_previous_ones():
    a, i = BurpParser()._parse_plaintext(PARTIAL)
    dep = next(f for f in a + i if f.title.startswith("Vulnerable JavaScript dependency"))
    assert dep.target == "Not recorded"


# -- pentest-report tables ------------------------------------------------------

def test_a_table_without_a_remediation_column_gives_no_remediation():
    from src.core.parsers.pentest_report_parser import PentestReportParser
    text = ("Vulnerability Assessment Report\n"
            "CVE Number | Vuln Description | RHEL severity | Fix Release\n"
            "CVE-2021-22543 | RHEL 7 : kernel (RHSA-2021:3801) | Important | \"Quarterly patch fix (April)\"\n"
            "CVE-2016-4658 | RHEL 7 : libxml2 (RHSA-2021:3810) | Important | \"Quarterly patch fix (April)\"\n")
    a, i = PentestReportParser().parse("report.docx", text)
    assert a and all(f.remediation == "" for f in a + i), [f.remediation for f in a + i]


