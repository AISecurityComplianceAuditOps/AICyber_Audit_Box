def _burp_pdf():
    act, info = BurpParser()._parse_plaintext(BURP_PDF)
    return {f.target.split(" ")[0]: f for f in act + info}


# -- the parsers --------------------------------------------------------------

def test_an_issue_detail_is_the_proof_whole_when_the_exchange_is_not_in_the_text():
    ev = _burp_pdf()["https://shop.test/search/2"].evidence
    assert ev == "[Issue detail]\n" + DETAIL
    assert ev.endswith("other obstacles that may be in place.")


def test_every_request_and_response_is_kept_whole():
    ev = _burp_pdf()["https://shop.test/search/3"].evidence
    assert [m for m in re.findall(r"\[HTTP [^\]]+\]", ev)] == [
        "[HTTP Request 1]", "[HTTP Response 1]", "[HTTP Request 2]", "[HTTP Response 2]"]
    assert REQUEST in ev and RESPONSE in ev
    assert ev.rstrip().endswith("END-OF-RESPONSE-2")


def test_the_last_response_stops_at_the_reports_closing_line():
    ev = _burp_pdf()["https://shop.test/search/3"].evidence
    assert "Report generated by Burp Suite" not in ev and "Leftover" not in ev


def test_a_burp_xml_exchange_is_kept_whole():
    xml = ("<?xml version='1.0'?><issues><issue><name>SQL injection</name><host>https://shop.test</host>"
           "<path>/filter</path><severity>High</severity><confidence>Firm</confidence>"
           "<issueDetail>The category parameter is injectable.</issueDetail><requestresponse>"
           f"<request base64=\"false\"><![CDATA[{REQUEST}]]></request>"
           f"<response base64=\"true\">{base64.b64encode(RESPONSE.encode()).decode()}</response>"
           "</requestresponse></issue></issues>")
    act, _info = BurpParser()._parse_xml(xml)
    ev = act[0].evidence
    assert ev.startswith("[HTTP Request]\n") and REQUEST in ev
    assert "[HTTP Response]\n" + RESPONSE in ev


def test_a_burp_html_exchange_is_kept_whole():
    html = ("<html><body><span class=\"BODH0\" id=\"1\">1.&nbsp;SQL injection</span>"
            "<h2>Summary</h2><table class=\"summary_table\"><tbody>"
            "<tr><td>Severity:&nbsp;&nbsp;</td><td><b>High</b></td></tr>"
            "<tr><td>Confidence:&nbsp;&nbsp;</td><td><b>Firm</b></td></tr>"
            "<tr><td>Host:&nbsp;&nbsp;</td><td><b>https://shop.test</b></td></tr>"
            "<tr><td>Path:&nbsp;&nbsp;</td><td><b>/filter</b></td></tr></tbody></table>"
            "<h2>Issue detail</h2><span class=\"TEXT\">The category parameter is injectable.</span>"
            # Burp escapes the exchange in its HTML report.
            f"<h2>Request 1</h2><div class=\"rr_div\">{escape(REQUEST)}</div>"
            f"<h2>Response 1</h2><div class=\"rr_div\">{escape(RESPONSE)}</div>"
            f"<h2>Request 2</h2><div class=\"rr_div\">{escape(REQUEST)}</div>"
            f"<h2>Response 2</h2><div class=\"rr_div\">{escape(RESPONSE.replace('-1', '-2'))}</div>"
            "</body></html>")
    act, info = BurpParser()._parse_html(html)
    ev = (act + info)[0].evidence
    assert ev.count("[Response ") == 2 and RESPONSE in ev
    assert ev.rstrip().endswith("END-OF-RESPONSE-2")


