"""A VAPT finding's proof of concept is kept whole, in labelled parts.

It was cut at every step: the Burp parser kept 500 characters of an issue
detail (a card ended "You shoul"), 700 of each request and response and only
the first two exchanges; the HTML and XML paths 400 and 1200; Nessus, Qualys,
sqlmap and the code scanners 500 to 1500; the worker cut again at 1200 and the
reports at 2500. Now the proof is whole, each request / response / issue detail
under its own label on the card and in both reports. Only a raw HTTP body past
20,000 characters is cut, at a line, saying how much is left out.

The page's own functions are run under Node where it is available.
"""
