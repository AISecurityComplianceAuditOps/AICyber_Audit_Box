def test_the_worker_stores_the_whole_output(tmp_path, monkeypatch):
    eng = create_engine("sqlite:///" + str(tmp_path / "vapt.db"))
    Base.metadata.create_all(eng)
    S = sessionmaker(bind=eng)
    monkeypatch.setattr(worker, "SessionLocal", S)
    s = S()
    s.add(AuditReport(session_id="p1", session_title="p1", framework="VAPT"))
    s.commit()
    s.close()
    worker._run_fast_technical_vapt_bg("p1", [{"name": "scan.nessus", "bytes": NESSUS.encode(), "text": None}],
                                       selected_sls=[], framework="VAPT")
    s = S()
    try:
        rep = s.query(AuditReport).filter(AuditReport.session_id == "p1").first()
        snip = s.query(Finding).filter(Finding.report_id == rep.id).first().evidence_snippet
    finally:
        s.close()
    assert snip.endswith("Plugin Output:\n" + LONG_OUTPUT.strip())


