# -- the page -----------------------------------------------------------------

def _function(src, name):
    start = src.index(f"function {name}(")
    depth, i = 0, src.index("{", start)
    while True:
        ch = src[i]
        depth += ch == "{"
        depth -= ch == "}"
        i += 1
        if depth == 0:
            return src[start:i]


def _run(expr):
    node = shutil.which("node")
    if not node:
        pytest.skip("node not available")
    src = io.open(APP_JS, encoding="utf-8").read()
    const = src[src.index("const _POC_LABEL_RE"):]
    const = const[:const.index("\n") + 1]
    script = "\n".join([
        "function escapeHtml(s) { return String(s).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;'); }",
        const, _function(src, "pocSections"), _function(src, "pocHtml")])
    script += "\nprocess.stdout.write(JSON.stringify(%s));\n" % expr
    out = subprocess.run([node, "-e", script], capture_output=True, text=True, timeout=30)
    assert out.returncode == 0, out.stderr
    return json.loads(out.stdout)


