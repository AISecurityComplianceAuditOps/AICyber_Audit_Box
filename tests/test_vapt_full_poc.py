def test_only_a_page_sized_body_is_cut_and_it_says_so():
    assert full_poc("x" * 50) == "x" * 50
    big = "\n".join("line %05d %s" % (n, "y" * 40) for n in range(1000))
    out = full_poc(big)
    assert len(out) < POC_MAX_CHARS + 100
    left = int(re.search(r"\[\.\.\. (\d+) more characters in the source file\]$", out).group(1))
    kept = out[:out.rindex("\n[...")]
    assert big.startswith(kept) and len(kept) + left == len(big)
    assert kept.endswith("y" * 40)                        # cut at a line, not mid-line


